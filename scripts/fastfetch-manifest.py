#!/usr/bin/env python3
"""Turn the vendored fastfetch .inc files into a manifest raba-gen can read.

fastfetch declares its logos in C: each entry names the logo and its aliases,
points at an art file through a macro, and gives a default colour per $N slot.
None of that survives into the .txt files, so it has to be parsed out here
rather than guessed at build time.

Colours are kept exactly as fastfetch would emit them -- "34", "90", "38;5;15",
"38;2;198;151;66" -- so the manifest stays faithful to upstream and raba-gen
does its own downsampling, with the adjustments reported as usual.

usage: scripts/fastfetch-manifest.py vendor/fastfetch-logos
"""
import re
import sys
from pathlib import Path

COLOUR = {
    "BLACK": "30", "RED": "31", "GREEN": "32", "YELLOW": "33",
    "BLUE": "34", "MAGENTA": "35", "CYAN": "36", "WHITE": "37",
    "DEFAULT": "39",
    "LIGHT_BLACK": "90", "LIGHT_RED": "91", "LIGHT_GREEN": "92",
    "LIGHT_YELLOW": "93", "LIGHT_BLUE": "94", "LIGHT_MAGENTA": "95",
    "LIGHT_CYAN": "96", "LIGHT_WHITE": "97",
}

# Entries are delimited by the #ifdef guard around each one, which is the file's
# real structure. Matching on braces instead gets lost in the nested .colors
# block and silently drops entries -- Xenia was the one that noticed.
GUARD = re.compile(r"^\s*#ifdef\s+(FASTFETCH_DATATEXT_LOGO_[A-Z0-9_]+)\s*$", re.M)
NAME = re.compile(r'"((?:[^"\\]|\\.)*)"')
LINES = re.compile(r"\.lines\s*=\s*([A-Z0-9_]+)")


def unescape(text):
    """Undo C string escapes without touching UTF-8. Going through
    unicode_escape would decode the bytes as latin-1 and turn Adelie's
    accented e into mojibake."""
    out, i = [], 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            out.append(text[i + 1])
            i += 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def braced(text, start):
    """The contents of the brace group that opens at or after `start`."""
    open_at = text.find("{", start)
    if open_at < 0:
        return ""
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_at + 1:i]
    return ""


def field(chunk, key):
    at = chunk.find("." + key)
    return braced(chunk, at) if at >= 0 else ""


def colour_tokens(block):
    """Each .colors entry, as the SGR parameters fastfetch would emit."""
    out = []
    for raw in re.finditer(
        r"FF_COLOR_FG_(256|RGB)\s*((?:\"(?:[^\"]*)\"\s*)+)|FF_COLOR_FG_([A-Z_]+)", block
    ):
        kind, literal, plain = raw.group(1), raw.group(2), raw.group(3)
        if plain:
            if plain not in COLOUR:
                raise SystemExit(f"unknown colour constant FF_COLOR_FG_{plain}")
            out.append(COLOUR[plain])
        else:
            value = "".join(NAME.findall(literal or ""))
            out.append(("38;5;" if kind == "256" else "38;2;") + value)
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    root = Path(sys.argv[1])
    ascii_dir = root / "ascii"

    # The build turns adelie.txt into FASTFETCH_DATATEXT_LOGO_ADELIE.
    by_macro = {}
    for path in sorted(ascii_dir.rglob("*.txt")):
        by_macro.setdefault("FASTFETCH_DATATEXT_LOGO_" + path.stem.upper(), path)

    rows, missing = [], []
    for inc in sorted(ascii_dir.glob("*.inc")):
        text = inc.read_text(encoding="utf-8")
        bounds = [(m.start(), m.group(1)) for m in GUARD.finditer(text)]
        for index, (start, guard) in enumerate(bounds):
            end = bounds[index + 1][0] if index + 1 < len(bounds) else len(text)
            chunk = text[start:end]
            names = [unescape(n) for n in NAME.findall(field(chunk, "names"))]
            macro_match = LINES.search(chunk)
            if not names:
                continue
            macro = macro_match.group(1) if macro_match else guard
            path = by_macro.get(macro)
            if path is None:
                missing.append((names[0], macro))
                continue
            colours = colour_tokens(field(chunk, "colors"))
            rows.append((names[0], names[1:], path.relative_to(root).as_posix(), colours))

    rows.sort(key=lambda r: r[0].lower())
    # Colours are comma-separated, not semicolon-separated: an SGR value is
    # itself semicolon-separated, so "38;5;36;38;5;36" could be read as one
    # colour or as two. Commas never appear inside one.
    out = ["# name\taliases\tfile\tcolors",
           "# generated by scripts/fastfetch-manifest.py; do not edit",
           "# colors are SGR parameters as fastfetch emits them, comma-separated"]
    for name, aliases, path, colours in rows:
        for colour in colours:
            if "," in colour or "\t" in colour:
                raise SystemExit(f"{name}: colour {colour!r} breaks the manifest format")
        out.append("\t".join([name, ",".join(aliases), path, ",".join(colours)]))
    (root / "manifest.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")

    used = {r[2] for r in rows}
    orphans = sorted(
        p.relative_to(root).as_posix() for p in ascii_dir.rglob("*.txt")
        if p.relative_to(root).as_posix() not in used
    )
    print(f"{len(rows)} logos, {sum(len(r[1]) for r in rows)} aliases")
    if missing:
        print(f"WARNING: {len(missing)} entries with no art file: {missing[:5]}")
    if orphans:
        print(f"note: {len(orphans)} art files no entry references: {orphans[:5]}")


main()
